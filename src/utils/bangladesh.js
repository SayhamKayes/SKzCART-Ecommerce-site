export function getThanasForDistrict(district) {
  if (!district) return DISTRICT_THANAS.Dhaka || [];
  if (DISTRICT_THANAS[district]) return DISTRICT_THANAS[district];
  const matchedKey = Object.keys(DISTRICT_THANAS).find(
    (k) => k.toLowerCase() === district.toLowerCase()
  );
  return matchedKey ? DISTRICT_THANAS[matchedKey] : (DISTRICT_THANAS.Dhaka || []);
}

export function normalizeBangladeshPhone(input) {
  if (!input) return '';
  let cleaned = String(input).replace(/\D/g, '');
  if (cleaned.startsWith('880')) {
    cleaned = cleaned.substring(2);
  }
  if (cleaned.startsWith('80') && cleaned.length === 12) {
    cleaned = cleaned.substring(1);
  }
  return cleaned;
}

export function isValidBangladeshPhone(phone) {
  const normalized = normalizeBangladeshPhone(phone);
  return /^01[3-9]\d{8}$/.test(normalized);
}

export function calculateDeliveryFee(district, area = '') {
  const normDistrict = (district || '').trim().toLowerCase();
  const normArea = (area || '').trim().toLowerCase();

  if (normDistrict === 'dhaka') {
    const isSuburb = DHAKA_SUBURBS.some((sub) => normArea.includes(sub));
    if (isSuburb) {
      return { zone: 'sub_dhaka', fee: 100 };
    }
    return { zone: 'inside_dhaka', fee: 70 };
  }

  if (
    normDistrict === 'gazipur' ||
    normDistrict === 'narayanganj' ||
    normDistrict === 'munshiganj' ||
    normDistrict === 'manikganj' ||
    normDistrict === 'narsingdi'
  ) {
    return { zone: 'sub_dhaka', fee: 100 };
  }

  return { zone: 'outside_dhaka', fee: 130 };
}

export function formatBDT(amount) {
  return `৳${Math.round(amount || 0).toLocaleString('en-IN')}`;
}

export function toBengaliNumber(num) {
  if (num === undefined || num === null) return '';
  return String(num);
}

/**
 * Format any timestamp, date string, or Date object into Bangladesh Standard Time (BDT - Asia/Dhaka)
 * Example outputs:
 * - English: "06 Oct 2026, 02:10 AM" (or standard date/time)
 * - Localized format
 */
export function formatBDTDateTime(dateInput, isEnglish = true, formatType = 'standard') {
  if (!dateInput) return '—';
  try {
    let date;
    if (dateInput instanceof Date) {
      date = dateInput;
    } else {
      let str = String(dateInput).trim();
      if (!str.includes('T') && str.includes(' ')) {
        str = str.replace(' ', 'T');
      }
      date = new Date(str);
    }

    if (isNaN(date.getTime())) {
      return String(dateInput);
    }

    const dOpt = { timeZone: 'Asia/Dhaka', year: 'numeric', month: 'short', day: '2-digit' };
    const tOpt = { timeZone: 'Asia/Dhaka', hour: '2-digit', minute: '2-digit', hour12: true };

    const locale = 'en-GB';
    const datePart = new Intl.DateTimeFormat(locale, dOpt).format(date);
    const timePart = new Intl.DateTimeFormat(locale, tOpt).format(date);

    if (formatType === 'timeOnly') return timePart;
    if (formatType === 'dateOnly') return datePart;

    return `${datePart}, ${timePart}`;
  } catch {
    return String(dateInput);
  }
}

export function assessOrderRisk(phone, address, total, paymentMethod) {
  let score = 10;
  const factors = [];

  const normalized = normalizeBangladeshPhone(phone);
  if (!isValidBangladeshPhone(normalized)) {
    score += 50;
    factors.push('Invalid or suspicious phone number format');
  }

  if ((address || '').trim().length < 10) {
    score += 25;
    factors.push('Short or incomplete street address');
  }

  if (total > 8000 && paymentMethod === 'COD') {
    score += 25;
    factors.push('High value Cash on Delivery order (>৳8,000)');
  }

  if (paymentMethod !== 'COD') {
    score = Math.max(5, score - 20);
  }

  return {
    riskScore: Math.min(100, score),
    riskFactors: factors.length > 0 ? factors : ['Low risk profile - verified local operator pattern'],
  };
}
