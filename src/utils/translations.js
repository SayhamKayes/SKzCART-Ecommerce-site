/**
 * Returns the English product name
 */
export function getLocalizedProductName(product) {
  if (!product) return '';
  if (product.name && /[a-zA-Z]/.test(product.name)) {
    return product.name;
  }
  if (product.englishName && /[a-zA-Z]/.test(product.englishName)) {
    return product.englishName;
  }
  return product.name || product.englishName || product.nameBn || product.bengaliName || '';
}

